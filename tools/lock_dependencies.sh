#!/usr/bin/env bash
#
# Regenerates auto-install/constraints.txt: the exact version of every Python
# package the grill installs, direct and indirect.  Run it only when preparing
# a new release, after changing auto-install/requirements.txt, then:
#   - run the tests and try the release on the grill,
#   - add a build to updater/updater_manifest.json listing the changed pins,
#     so installed grills get them with the OTA update.
#
# Use Python 3.13 (Debian 13 / Armbian trixie, the grill's Python).
# numpy and scipy are left out: on the grill they come from Debian (python3-scipy).

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY="${PYTHON:-python3}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$PY" -c 'import sys; v=sys.version_info; print(f"Python {v.major}.{v.minor}"); sys.exit(0 if (v.major, v.minor) == (3, 13) else 1)' \
	|| { echo "Use Python 3.13 (PYTHON=/path/to/python3.13)" >&2; exit 1; }

"$PY" -m venv "$TMP/venv"
"$TMP/venv/bin/pip" install --quiet --upgrade pip
# Same set the installer puts in the grill's virtual environment
"$TMP/venv/bin/pip" install --quiet -r "$ROOT/auto-install/requirements.txt" "gpiod>=2.2,<3"

{
	echo "# Exact versions of every Python package installed on the grill (direct and indirect)."
	echo "# Generated by tools/lock_dependencies.sh on $(date -u +%Y-%m-%d) with $("$PY" --version)."
	echo "# Used as a constraints file by the installer, the updater and the wizard:"
	echo "# libraries change only with a new release, never on their own."
	"$TMP/venv/bin/pip" freeze --exclude-editable \
		| grep -viE '^(numpy|scipy|pip|setuptools|wheel)==' \
		| sort -f
} > "$ROOT/auto-install/constraints.txt"

echo "Written auto-install/constraints.txt ($(grep -vc '^#' "$ROOT/auto-install/constraints.txt") packages)"
