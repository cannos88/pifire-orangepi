'''
nmcli wrapper used by the Wi-Fi service.

Every call goes through `run`, so the tests replace it with a fake.  Output is
read in terse mode (-t), where ':' inside a field is escaped as '\\:'.
'''

import logging
import subprocess

from . import AP_ADDRESS, AP_CONNECTION, AP_SSID

log = logging.getLogger('wifi')

OWN_PREFIX = 'pifire-'   # connections created from the web app


def split_terse(line):
	''' Split one line of `nmcli -t` output on unescaped colons. '''
	fields, current, escaped = [], [], False
	for ch in line:
		if escaped:
			current.append(ch)
			escaped = False
		elif ch == '\\':
			escaped = True
		elif ch == ':':
			fields.append(''.join(current))
			current = []
		else:
			current.append(ch)
	fields.append(''.join(current))
	return fields


def default_run(args, timeout=30):
	''' Run nmcli and return (returncode, stdout, stderr). '''
	try:
		proc = subprocess.run(['nmcli'] + list(args), capture_output=True, text=True, timeout=timeout)
		return proc.returncode, proc.stdout, proc.stderr
	except FileNotFoundError:
		return 127, '', 'nmcli not found (NetworkManager is not installed)'
	except subprocess.TimeoutExpired:
		return 124, '', 'nmcli timed out'


class NetworkManagerCLI:
	def __init__(self, ifname=None, run=default_run):
		self.run = run
		self._ifname = ifname

	# ---------------------------------------------------------------- basics

	def available(self):
		rc, _, _ = self.run(['-t', 'general', 'status'], timeout=10)
		return rc == 0

	@property
	def ifname(self):
		if self._ifname is None:
			rc, out, _ = self.run(['-t', '-f', 'DEVICE,TYPE', 'device'], timeout=10)
			for line in out.splitlines() if rc == 0 else []:
				fields = split_terse(line)
				if len(fields) >= 2 and fields[1] == 'wifi':
					self._ifname = fields[0]
					break
			else:
				return 'wlan0'
		return self._ifname

	def status(self):
		'''
		{'device', 'state', 'connection', 'connected', 'ap', 'ip'}
		connected: associated to a network that is not our access point.
		'''
		info = {'device': self.ifname, 'state': 'unknown', 'connection': '', 'connected': False, 'ap': False, 'ip': ''}
		rc, out, _ = self.run(['-t', '-f', 'DEVICE,TYPE,STATE,CONNECTION', 'device'], timeout=10)
		if rc != 0:
			info['state'] = 'unavailable'
			return info
		for line in out.splitlines():
			fields = split_terse(line)
			if len(fields) >= 4 and fields[0] == info['device']:
				info['state'] = fields[2]
				info['connection'] = fields[3] if fields[3] != '--' else ''
				break
		info['ap'] = info['connection'] == AP_CONNECTION
		info['connected'] = info['state'].startswith('connected') and not info['ap'] and info['connection'] != ''
		if info['state'].startswith('connected'):
			rc, out, _ = self.run(['-g', 'IP4.ADDRESS', 'device', 'show', info['device']], timeout=10)
			if rc == 0 and out.strip():
				info['ip'] = out.strip().split('|')[0].strip().split('/')[0]
		return info

	def current_ssid(self, connection):
		if not connection:
			return ''
		rc, out, _ = self.run(['-g', '802-11-wireless.ssid', 'connection', 'show', connection], timeout=10)
		return out.strip() if rc == 0 else connection

	# ---------------------------------------------------------------- scanning

	def scan(self, rescan=True):
		''' Visible networks, strongest first: [{'ssid', 'signal', 'secure'}] '''
		args = ['-t', '-f', 'SSID,SIGNAL,SECURITY', 'device', 'wifi', 'list', 'ifname', self.ifname,
				'--rescan', 'yes' if rescan else 'no']
		rc, out, err = self.run(args, timeout=40)
		if rc != 0:
			log.warning(f'Wi-Fi scan failed: {err.strip()}')
			return []
		best = {}
		for line in out.splitlines():
			fields = split_terse(line)
			if len(fields) < 3:
				continue
			ssid, signal, security = fields[0], fields[1], fields[2]
			if not ssid or ssid == AP_SSID:
				continue
			try:
				signal = int(signal)
			except ValueError:
				signal = 0
			secure = security not in ('', '--')
			if ssid not in best or signal > best[ssid]['signal']:
				best[ssid] = {'ssid': ssid, 'signal': signal, 'secure': secure}
		return sorted(best.values(), key=lambda n: -n['signal'])

	# ---------------------------------------------------------------- saved networks

	def saved_networks(self):
		''' Saved Wi-Fi client connections: [{'name', 'ssid', 'removable'}] '''
		rc, out, _ = self.run(['-t', '-f', 'NAME,TYPE', 'connection', 'show'], timeout=10)
		if rc != 0:
			return []
		saved = []
		for line in out.splitlines():
			fields = split_terse(line)
			if len(fields) < 2 or fields[1] not in ('802-11-wireless', 'wifi'):
				continue
			name = fields[0]
			if name == AP_CONNECTION:
				continue
			ssid = self.current_ssid(name)
			# Connections generated by netplan live in /run and are rewritten at boot
			saved.append({'name': name, 'ssid': ssid, 'removable': not name.startswith('netplan-')})
		return saved

	def add_network(self, ssid, password='', activate=False, wait=40):
		'''
		Save a network (replacing one saved from the web app with the same SSID)
		and, if activate, connect to it now.  Returns (ok, error message).
		'''
		name = OWN_PREFIX + ssid
		self.run(['connection', 'delete', 'id', name], timeout=15)
		args = ['connection', 'add', 'type', 'wifi', 'ifname', self.ifname, 'con-name', name,
				'ssid', ssid, 'connection.autoconnect', 'yes', 'connection.autoconnect-priority', '10']
		if password:
			args += ['wifi-sec.key-mgmt', 'wpa-psk', 'wifi-sec.psk', password]
		rc, _, err = self.run(args, timeout=20)
		if rc != 0:
			return False, err.strip() or 'nmcli connection add failed'
		if not activate:
			return True, ''
		rc, _, err = self.run(['--wait', str(wait), 'connection', 'up', 'id', name], timeout=wait + 10)
		if rc != 0:
			return False, err.strip() or 'connection failed'
		return True, ''

	def forget(self, name):
		rc, _, err = self.run(['connection', 'delete', 'id', name], timeout=15)
		return rc == 0, err.strip()

	# ---------------------------------------------------------------- access point

	def ensure_ap(self):
		rc, _, _ = self.run(['connection', 'show', AP_CONNECTION], timeout=10)
		if rc == 0:
			return True
		args = ['connection', 'add', 'type', 'wifi', 'ifname', self.ifname, 'con-name', AP_CONNECTION,
				'ssid', AP_SSID, 'connection.autoconnect', 'no',
				'802-11-wireless.mode', 'ap', '802-11-wireless.band', 'bg',
				'ipv4.method', 'shared', 'ipv4.addresses', f'{AP_ADDRESS}/24', 'ipv6.method', 'disabled']
		rc, _, err = self.run(args, timeout=20)
		if rc != 0:
			log.error(f'Cannot create the emergency access point: {err.strip()}')
		return rc == 0

	def start_ap(self):
		if not self.ensure_ap():
			return False
		rc, _, err = self.run(['--wait', '30', 'connection', 'up', 'id', AP_CONNECTION], timeout=40)
		if rc != 0:
			log.error(f'Cannot start the emergency access point: {err.strip()}')
		return rc == 0

	def stop_ap(self):
		rc, _, _ = self.run(['connection', 'down', 'id', AP_CONNECTION], timeout=20)
		return rc == 0
